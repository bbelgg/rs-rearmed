#!/bin/bash
# Usage: gen-tbd.sh <out.tbd>
#
# Writes a TAPI text stub for /usr/lib/libstdc++.6.dylib from the export trie of
# the copy in this machine's dyld shared cache. The macOS SDK stopped shipping
# libstdc++.tbd (Xcode 10), but the library itself is still in the arm64e and
# x86_64 shared caches, so anything that wants to *link* against it (the shim's
# -reexport_library, or a relinked arm64 game binary) needs this stub.
#
# Symbols libstdc++ re-exports from libc++abi (__cxa_*, operator new/delete,
# std::exception, ...) are not listed; the stub declares libc++abi as a
# re-exported library instead, the same way the real dylib does.
set -euo pipefail

[[ $# -eq 1 ]] || { echo "usage: $0 <out.tbd>" >&2; exit 64; }
out=$1
lib=/usr/lib/libstdc++.6.dylib

exports=$(xcrun dyld_info -exports "$lib" 2>/dev/null) \
    || { echo "error: dyld_info can't read $lib from the shared cache" >&2; exit 1; }

# Lines look like "0x35906150  __ZGVNSt10moneypunctIcLb0EE2idE [weak-def]" or
# "[re-export] __Znwm (from libc++abi)".
own=$(awk '$1 ~ /^0x/ { print $2 }' <<<"$exports" | sort -u)
weak=$(awk '$1 ~ /^0x/ && /\[weak-def\]/ { print $2 }' <<<"$exports" | sort -u)
reexp=$(awk '$1 == "[re-export]" { print $2 }' <<<"$exports" | wc -l | tr -d ' ')
[[ -n "$own" ]] || { echo "error: no exports parsed from $lib" >&2; exit 1; }

# Versions as recorded in the game's LC_LOAD_DYLIB (it requires compat >= 7.0.0;
# macOS 27 ships 105.4.0 / 7.0.0).
cur=104.1.0 compat=7.0.0

# Writes "[ a, b, c ]" with a few symbols per line, as tapi does.
yaml_list() {
    awk -v indent="$1" 'BEGIN { ORS = "" } NF {
            if (n > 0) { print ","; if (n % 3 == 0) printf "\n%s", indent; else print " " }
            print "\x27" $0 "\x27"; n++ }
        END { print " ]\n" }' | sed '1s/^/[ /'
}

regular=$(comm -23 <(echo "$own") <(echo "$weak"))
targets='[ x86_64-macos, arm64-macos, arm64e-macos ]'
{
    echo "--- !tapi-tbd"
    echo "# Generated by shims/libstdcxx/tools/gen-tbd.sh from the dyld shared cache"
    echo "# $(wc -l <<<"$own" | tr -d ' ') own exports, $reexp re-exported from libc++abi."
    echo "tbd-version:     4"
    echo "targets:         $targets"
    echo "install-name:    '$lib'"
    echo "current-version: $cur"
    echo "compatibility-version: $compat"
    echo "reexported-libraries:"
    echo "  - targets:         $targets"
    echo "    libraries:       [ '/usr/lib/libc++abi.dylib' ]"
    echo "exports:"
    echo "  - targets:         $targets"
    printf "    symbols:         "
    yaml_list "                       " <<<"$regular"
    if [[ -n "$weak" ]]; then
        printf "    weak-symbols:    "
        yaml_list "                       " <<<"$weak"
    fi
    echo "..."
} >"$out"
echo "wrote $out ($(wc -l <<<"$own" | tr -d ' ') symbols)"
