#!/usr/bin/env python3
"""Generate the X-macro table of the GL/CGL functions libRSOpenGL wraps.

    gen-gl-api.py <game-gl-imports.txt> <extra-gl-imports.txt> <sdk-headers-dir> <out.inc>
                  [<out-metal-stubs.c>]

The table is the game's imports (game-gl-imports.txt, in that order) followed
by the extra functions the Cg shim, the shell, the overlay and the tests call
(extra-gl-imports.txt; names already in the game list are skipped). For every
name, find its prototype in the SDK's OpenGL.framework headers and emit

    RS_GL_FN(ret, name, (typed params), (arg names))   or, for void functions,
    RS_GL_VOID(name, (typed params), (arg names))

The extras sit inside #ifndef RS_GL_GAME_ONLY, so an includer that defines it
(the spy) sees only the game's imports; RS_GL_GAME_COUNT is the number of game
imports, which come first, so RS_GL_IDX_<name> < RS_GL_GAME_COUNT marks one.
Includers define both macros before including the table, e.g. to declare,
wrap, forward or count every function (gl_api.h has helpers). Fails if any
name has no prototype, so a new import can't be silently dropped.

With <out-metal-stubs.c>, also write a weak rsmtl_<name> for every function
(the Metal backend's entry points, docs/METAL-DESIGN.md): it reports
"unimplemented <name>" once and returns 0. A strong definition in src/metal/
replaces it at link time.
"""
import re
import sys

# Headers that declare the functions themselves (gl3.h duplicates gl.h's core
# prototypes; glext.h adds the ARB/extension entry points the game uses).
# OpenGL.h declares CGLErrorString without "extern", hence the optional prefix.
HEADERS = ["gl.h", "glext.h", "gl3.h", "CGLCurrent.h", "OpenGL.h", "CGLContext.h", "CGLDevice.h"]

PROTO = re.compile(
    r"^\s*(?:(?:extern|GLAPI)\s+)?(?P<ret>[\w\s\*]+?)\s*(?:APIENTRY\s+)?\b(?P<name>(?:gl|CGL)\w+)\s*"
    r"\((?P<params>[^)]*)\)")

NULLABILITY = re.compile(r"\bOPENGL_(?:NULLABLE|NONNULL)\b")

# Weak Metal defaults that are right as they are (no "unimplemented" report): the
# Metal core shares nothing between contexts, so each is its own share group, and
# CGL engine switches are no-ops there.
METAL_DEFAULTS = {
    "CGLGetShareGroup": "return (CGLShareGroupObj)ctx;",
    "CGLDisable": "(void)ctx;\n    (void)pname;\n    return kCGLNoError;",
}


def arg_names(params):
    params = params.strip()
    if params in ("", "void", "GLvoid"):
        return [], ""
    names = []
    for p in params.split(","):
        m = re.search(r"(\w+)\s*(\[\d*\])?\s*$", p.strip())
        if not m:
            raise ValueError(f"can't name parameter {p!r}")
        names.append(m.group(1))
    return names, params


def read_list(path):
    return [l.strip()[1:] for l in open(path) if l.strip().startswith("_")]


def main():
    if len(sys.argv) not in (5, 6):
        sys.exit(__doc__)
    game_path, extra_path, hdr_dir, out_path = sys.argv[1:5]
    stubs_path = sys.argv[5] if len(sys.argv) == 6 else None
    game = read_list(game_path)
    extra = [n for n in dict.fromkeys(read_list(extra_path)) if n not in set(game)]

    protos = {}
    for h in HEADERS:
        for line in open(f"{hdr_dir}/{h}", errors="replace"):
            m = PROTO.match(line)
            if m and m.group("name") not in protos:
                # Drop the CGL headers' nullability macros: once one pointer in a file has
                # one, clang wants them on every pointer (-Wnullability-completeness).
                ret, params = (" ".join(NULLABILITY.sub(" ", t).split()) for t in m.group("ret", "params"))
                protos[m.group("name")] = (ret, params)

    missing = [n for n in game + extra if n not in protos]
    if missing:
        sys.exit("no prototype for: " + " ".join(missing))

    def entry(n):
        ret, params = protos[n]
        names, params = arg_names(params)
        sig = f"{n}, ({params or 'void'}), ({', '.join(names)})"
        return f"RS_GL_VOID({sig})\n" if ret == "void" else f"RS_GL_FN({ret}, {sig})\n"

    with open(out_path, "w") as out:
        out.write("// Generated by tools/gen-gl-api.py from game-gl-imports.txt, extra-gl-imports.txt\n"
                  "// and the SDK's OpenGL.framework headers. Do not edit.\n"
                  "// RS_GL_FN(ret, name, (params), (args)) / RS_GL_VOID(name, (params), (args))\n")
        out.write(f"#ifndef RS_GL_GAME_COUNT\n#define RS_GL_GAME_COUNT {len(game)}\n#endif\n")
        out.write("// The game's imports\n")
        for n in game:
            out.write(entry(n))
        out.write("#ifndef RS_GL_GAME_ONLY\n// Extra: Cg shim, shell, overlay, tests\n")
        for n in extra:
            out.write(entry(n))
        out.write("#endif\n")

    if stubs_path:
        with open(stubs_path, "w") as out:
            out.write(
                "// Generated by tools/gen-gl-api.py. Do not edit.\n"
                "// Weak Metal-backend entry points (docs/METAL-DESIGN.md): each reports\n"
                "// \"unimplemented <name>\" once and returns 0. A strong rsmtl_<name> anywhere in\n"
                "// libRSOpenGL (src/metal/) replaces it; rsgl.c routes every wrapper to these\n"
                "// with RS_GL_BACKEND=metal.\n"
                "#include \"gl_api.h\"\n\n"
                "void rsmtl_unimplemented(int idx, const char *name);\n\n"
                "#define RSMTL_STUB __attribute__((weak, visibility(\"hidden\")))\n")
            for n in game + extra:
                ret, params = protos[n]
                names, params = arg_names(params)
                out.write(f"RSMTL_STUB {ret} rsmtl_{n}({params or 'void'}) {{\n")
                if n in METAL_DEFAULTS:
                    out.write(f"    {METAL_DEFAULTS[n]}\n}}\n")
                    continue
                for a in names:
                    out.write(f"    (void){a};\n")
                out.write(f"    rsmtl_unimplemented(RS_GL_IDX_{n}, \"{n}\");\n")
                if ret != "void":
                    out.write(f"    return ({ret})0;\n")
                out.write("}\n")

    print(f"{len(game)} game + {len(extra)} extra functions -> {out_path}"
          + (f", {stubs_path}" if stubs_path else ""))


if __name__ == "__main__":
    main()
