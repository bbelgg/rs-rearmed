#!/usr/bin/env python3
"""Generate an X-macro table of the GL/CGL functions the game imports.

    gen-gl-api.py <game-gl-imports.txt> <sdk-headers-dir> <out.inc>

For every name in the import list, find its prototype in the SDK's
OpenGL.framework headers and emit

    RS_GL_FN(ret, name, (typed params), (arg names))   or, for void functions,
    RS_GL_VOID(name, (typed params), (arg names))

Includers define both macros before including the table, e.g. to declare,
wrap, forward or count every function (gl_api.h has helpers). Fails if any import has no prototype,
so a new import can't be silently dropped.
"""
import re
import sys

# Headers that declare the functions themselves (gl3.h duplicates gl.h's core
# prototypes; glext.h adds the ARB/extension entry points the game uses).
HEADERS = ["gl.h", "glext.h", "gl3.h", "CGLCurrent.h", "OpenGL.h", "CGLContext.h"]

PROTO = re.compile(
    r"^\s*(?:extern|GLAPI)\s+(?P<ret>[\w\s\*]+?)\s*(?:APIENTRY\s+)?\b(?P<name>(?:gl|CGL)\w+)\s*"
    r"\((?P<params>[^)]*)\)")


def arg_names(params):
    params = params.strip()
    if params in ("", "void", "GLvoid"):
        return [], ""
    names = []
    for p in params.split(","):
        m = re.search(r"(\w+)\s*(\[\d*\])?\s*$", p.strip())
        if not m:
            raise ValueError(f"can't name parameter {p!r}")
        names.append(m.group(1))
    return names, params


def main():
    imports_path, hdr_dir, out_path = sys.argv[1:4]
    wanted = [l.strip()[1:] for l in open(imports_path) if l.strip().startswith("_")]

    protos = {}
    for h in HEADERS:
        for line in open(f"{hdr_dir}/{h}", errors="replace"):
            m = PROTO.match(line)
            if m and m.group("name") not in protos:
                protos[m.group("name")] = (" ".join(m.group("ret").split()), m.group("params"))

    missing = [n for n in wanted if n not in protos]
    if missing:
        sys.exit("no prototype for: " + " ".join(missing))

    with open(out_path, "w") as out:
        out.write("// Generated by tools/gen-gl-api.py from game-gl-imports.txt and the SDK's\n"
                  "// OpenGL.framework headers. Do not edit.\n"
                  "// RS_GL_FN(ret, name, (params), (args)) / RS_GL_VOID(name, (params), (args))\n")
        for n in wanted:
            ret, params = protos[n]
            names, params = arg_names(params)
            sig = f"{n}, ({params or 'void'}), ({', '.join(names)})"
            out.write(f"RS_GL_VOID({sig})\n" if ret == "void" else f"RS_GL_FN({ret}, {sig})\n")
    print(f"{len(wanted)} functions -> {out_path}")


if __name__ == "__main__":
    main()
