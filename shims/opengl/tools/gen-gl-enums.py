#!/usr/bin/env python3
"""Generate a sorted C table of GL enum names for the call tracer.

    gen-gl-enums.py <sdk-headers-dir> <out.inc>

Parses `#define GL_NAME value` from the SDK's gl.h/glext.h/gl3.h/gl3ext.h.
Several names share one value; the plain name wins over ARB, then EXT, then
vendor suffixes, then the shorter name.
"""
import re
import sys

DEF = re.compile(r"^\s*#\s*define\s+(GL_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b")


def rank(name):
    for i, suf in enumerate(("_ARB", "_EXT", "_OES", "_APPLE", "_NV", "_ATI", "_SGI")):
        if name.endswith(suf) or (suf + "_") in name:
            return i + 1
    return 0


def main():
    hdr, out = sys.argv[1], sys.argv[2]
    best = {}
    for h in ("gl.h", "glext.h", "gl3.h", "gl3ext.h"):
        try:
            text = open(f"{hdr}/{h}", errors="replace").read()
        except OSError:
            continue
        for line in text.splitlines():
            m = DEF.match(line)
            if not m:
                continue
            v = int(m.group(2), 0)
            if v > 0xFFFFFFFF:
                continue
            n = m.group(1)
            key = (rank(n), len(n), n)
            if v not in best or key < best[v][0]:
                best[v] = (key, n)
    with open(out, "w") as f:
        f.write("// generated by gen-gl-enums.py\n")
        for v in sorted(best):
            f.write('{0x%X, "%s"},\n' % (v, best[v][1]))


main()
