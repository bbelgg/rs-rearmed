#!/usr/bin/env python3
"""Whole-image generator: translate every function start of __text to C.

Usage: venv/bin/python -I gen_image.py IMAGE OUTDIR [options]
  --jobs N          worker processes (default: cpu count)
  --skip FILE       (repeatable) addresses (hex, one per line, # comments) an override
                    module defines F_<addr> for; not generated, but present in rc_table.
                    A line `ADDR drop` is not generated and NOT in rc_table either (dead
                    code in a replaced range; a remaining direct reference fails to link).
                    A line `ADDR wrap` is a hook point: generated as W_<addr>, and F_<addr>
                    (rc_table, direct calls) is a generated wrapper that runs the hooks
                    registered for it at run time around W_<addr> (runtime/rc_hook.h)
  --tso-ranges FILE lo-hi (hex) per line; TUs whose functions fall
                    in a range are compiled with -DRC_MO_TSO
  --o1 FILE         addresses of functions clang compiles badly at -O2; each goes
                    into its own TU, compiled at -O1
  --only lo-hi      only functions in this address range (experiments)
  --chunk-insns N   target instructions per TU (default 40000)
  --obj-dir DIR     where ninja puts objects (default: analysis/ws7/recomp/obj)
  --cflags "..."    extra compiler flags for every TU (e.g. -DRC_ABI_TRUST)
  --opt -O2         default optimisation level
  --lto "..."       flags for every TU except --o1 ones (e.g. -flto=thin; an -O1 TU stays a
                    native object so the link-time optimiser does not take it to -O2)
  --prof "..."      PGO flags for every TU (-fprofile-instr-generate / -fprofile-instr-use=F)
  --prof-dep FILE   the .profdata of --prof: TUs are rebuilt when it changes

Output in OUTDIR: decls.h, part_<firstaddr>.c, table.c, manifest.json, build.ninja.
TU files are rewritten only when their content changes.
"""
import argparse
import json
import multiprocessing as mp
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
RECOMP = os.path.normpath(os.path.join(HERE, ".."))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))
sys.path.insert(0, RECOMP)

PRELUDE = ("// Generated by tools/ws7/recomp/build/gen_image.py from the original x86_64 machine code.\n"
           "// Game-derived: build output only, never commit. Do not edit; regenerate.\n"
           '#include "rc_gen.h"\n\n')
SYM_RE = re.compile(r"\b([FI]_[0-9a-f]+)\(c\)")

_tr = None


def _init(img):
    global _tr
    from xlat.core import Translator
    _tr = Translator(img)


def _work(batch):
    from xlat.common import Unsupported
    out = []
    for f in batch:
        try:
            lines = _tr.function(f)
            n = int(re.search(r": (\d+) instructions", lines[0]).group(1))
            out.append((f, "ok", "", n, "\n".join(lines), sorted(_tr.callees)))
        except Unsupported as e:
            out.append((f, "stub", str(e).split(": ", 1)[-1][:300], 1, None, []))
        except Exception as e:  # translator bug: still must link
            out.append((f, "stub", "internal error: %s: %s" % (type(e).__name__, e), 1, None, []))
    return out


def stub_text(a, reason):
    r = reason.replace("\\", "\\\\").replace('"', "'").replace("\n", " ")
    return ('// 0x%x: stub\nvoid F_%x(rc_ctx *c) { rc_fail("untranslated: %s", 0x%xull); }\n'
            % (a, a, r, a))


def read_addrs(path, drop=None, wrap=None):
    """Hex addresses, one per line. With `drop` / `wrap` (sets), lines `ADDR drop` /
    `ADDR wrap` go there instead of into the returned set."""
    s = set()
    for ln in open(path):
        p = ln.split("#")[0].split()
        if not p:
            continue
        if len(p) > 1 and p[1] == "drop" and drop is not None:
            drop.add(int(p[0], 16))
        elif len(p) > 1 and p[1] == "wrap" and wrap is not None:
            wrap.add(int(p[0], 16))
        else:
            s.add(int(p[0], 16))
    return s


def read_ranges(path):
    r = []
    for ln in open(path):
        ln = ln.split("#")[0].strip()
        if ln:
            lo, hi = ln.split("-")
            r.append((int(lo, 16), int(hi, 16)))
    return r


def write_if_changed(path, text):
    try:
        if open(path).read() == text:
            return False
    except OSError:
        pass
    with open(path, "w") as f:
        f.write(text)
    return True


class Chunker:
    """Content-defined chunking so that a change in one function only
    perturbs nearby TUs: cut once `target/2` instructions are reached at a
    function whose address hashes to 0 mod 3, or at 1.5*target regardless."""

    def __init__(self, outdir, target, tso, o1, wrap=frozenset()):
        self.outdir, self.target, self.tso, self.o1, self.wrap = outdir, target, tso, o1, wrap
        self.cur, self.n, self.cls, self.first = [], 0, None, None
        self.chunks = []   # (name, tso, o1, ninsn, nfuncs)
        self.files = set()
        self.where = {}
        self.changed = 0

    def in_tso(self, a):
        return any(lo <= a < hi for lo, hi in self.tso)

    def add(self, a, ninsn, text, callees):
        cls = (self.in_tso(a), a in self.o1)
        if self.cur and (cls != self.cls or cls[1]):
            self.flush()
        self.cur.append((a, ninsn, text, callees))
        self.cls, self.n = cls, self.n + ninsn
        cut = (self.n >= self.target // 2 and (a * 2654435761 >> 8) % 3 == 0) or self.n >= self.target * 3 // 2
        if cut or cls[1]:
            self.flush()

    def flush(self):
        if not self.cur:
            return
        defined = {a for a, _, _, _ in self.cur}
        used = set()
        for _, _, t, cs in self.cur:
            used.update(SYM_RE.findall(t))
        protos = sorted(used | {"F_%x" % a for a in defined}   # uses may precede definitions
                        | {"W_%x" % a for a in defined & self.wrap})
        name = "part_%x" % self.cur[0][0]
        txt = PRELUDE + "".join("void %s(rc_ctx *c);\n" % s for s in protos) + "\n" + \
            "\n".join(t for _, _, t, _ in self.cur) + "\n"
        if write_if_changed(os.path.join(self.outdir, name + ".c"), txt):
            self.changed += 1
        self.files.add(name + ".c")
        for a, _, _, _ in self.cur:
            self.where[a] = name
        self.chunks.append((name, self.cls[0], self.cls[1], sum(x[1] for x in self.cur), len(self.cur)))
        self.cur, self.n, self.cls = [], 0, None


def write_ninja(args, outdir, chunks):
    obj = os.path.abspath(args.obj_dir)
    inc = os.path.join(RECOMP, "runtime")
    base = "-arch arm64 -fno-strict-aliasing -ffp-contract=off -I%s %s %s" % (inc, args.cflags, args.prof)
    # ninja rebuilds a TU when its command line changes; the profile is an implicit input
    dep = " | " + os.path.abspath(args.prof_dep) if args.prof_dep else ""
    L = ["# generated by gen_image.py", "ninja_required_version = 1.8",
         "cc = clang", "base = " + base, "opt = " + args.opt, "lto = " + args.lto,
         "rule cc", "  command = $cc $base $opt $lto $extra -MMD -MF $out.d -c $in -o $out",
         "  depfile = $out.d", "  deps = gcc", "  description = CC $in",
         "rule ar", "  command = rm -f $out && libtool -static -o $out $in", "  description = AR $out", ""]
    objs = []
    for name, tso, o1, _, _ in chunks + [("table", False, False, 0, 0)]:
        o = "%s/%s.o" % (obj, name)
        objs.append(o)
        extra = (" -DRC_MO_TSO" if tso else "")
        L.append("build %s: cc %s/%s.c%s" % (o, os.path.abspath(outdir), name, dep))
        if o1:
            L.append("  opt = -O1")
            L.append("  lto =")
        if extra:
            L.append("  extra =" + extra)
    L.append("build %s/libgame_rc.a: ar %s" % (obj, " ".join(objs)))
    L.append("default %s/libgame_rc.a" % obj)
    write_if_changed(os.path.join(outdir, "build.ninja"), "\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("outdir")
    ap.add_argument("--jobs", type=int, default=os.cpu_count())
    ap.add_argument("--skip", action="append", default=[])
    ap.add_argument("--tso-ranges")
    ap.add_argument("--o1")
    ap.add_argument("--only")
    ap.add_argument("--chunk-insns", type=int, default=40000)
    ap.add_argument("--obj-dir", default=os.path.join(ROOT, "analysis/ws7/recomp/obj"))
    ap.add_argument("--cflags", default="")
    ap.add_argument("--opt", default="-O2")
    ap.add_argument("--lto", default="")
    ap.add_argument("--prof", default="")
    ap.add_argument("--prof-dep")
    ap.add_argument("--batch", type=int, default=48)
    args = ap.parse_args()
    os.makedirs(args.outdir, exist_ok=True)
    t0 = time.time()
    from xlat.core import Translator
    tr = Translator(args.image)
    lo_t, hi_t = tr.text_lo, tr.text_hi
    starts = sorted(f for f in tr.img.fstarts if lo_t <= f < hi_t)
    if args.only:
        lo, hi = (int(x, 16) for x in args.only.split("-"))
        starts = [f for f in starts if lo <= f < hi]
    del tr
    skip, drop, wrap = set(), set(), set()
    for p in args.skip:
        skip |= read_addrs(p, drop, wrap)
    skip -= drop
    wrap -= drop
    skip -= wrap
    tso = read_ranges(args.tso_ranges) if args.tso_ranges else []
    o1 = read_addrs(args.o1) if args.o1 else set()
    todo = [f for f in starts if f not in skip and f not in drop]
    batches = [todo[i:i + args.batch] for i in range(0, len(todo), args.batch)]
    ch = Chunker(args.outdir, args.chunk_insns, tso, o1, wrap)
    hook_index = {a: i for i, a in enumerate(sorted(wrap))}
    status = {}      # addr -> (status, reason, ninsn, chunk)
    callees = set()
    pending_stubs = []

    def place(a, st, reason, n, text, cs):
        if st == "stub":
            text = stub_text(a, reason)
        if a in wrap:   # the original under another name, and F_<a> runs the hooks around it
            text = text.replace("void F_%x(rc_ctx *c) {" % a, "void W_%x(rc_ctx *c) {" % a, 1)
            text += "\nvoid F_%x(rc_ctx *c) { rc_hook_call(%d, c, W_%x); }\n" % (a, hook_index[a], a)
            st = "wrapped" if st == "ok" else st
        ch.add(a, n, text, cs)
        status[a] = [st, reason, n, None]
        callees.update(cs)

    with mp.Pool(args.jobs, _init, (args.image,)) as pool:
        done = 0
        for res in pool.imap(_work, batches):
            for a, st, reason, n, text, cs in res:
                place(a, st, reason, n, text, cs)
            done += len(res)
            if (done // args.batch) % 100 == 0:
                print("  %d/%d functions, %.0fs" % (done, len(todo), time.time() - t0), file=sys.stderr)
    # every F_x referenced must be defined: callees that are not function
    # starts (or are outside the generated set) get a stub
    known = set(status) | skip | drop
    for t in sorted(callees - known):
        if args.only and not (lo <= t < hi):
            continue
        place(t, "stub", "callee 0x%x is not a function start" % t, 1, None, [])
        starts.append(t)
    ch.flush()
    for s in skip:
        status[s] = ["skipped", "override", 0, None]
    # table.c
    allf = sorted((set(starts) | skip | set(status)) - drop)
    decls = ["// generated: prototypes of every translated function",
             '#include "rc.h"'] + ["void F_%x(rc_ctx *c);" % a for a in allf] + \
            ["void W_%x(rc_ctx *c);" % a for a in sorted(wrap)]
    write_if_changed(os.path.join(args.outdir, "decls.h"), "\n".join(decls) + "\n")
    tab = [PRELUDE.rstrip("\n"), '#include "decls.h"',
           "typedef struct { uint64_t vmaddr; rc_fn fn; } rc_entry;",
           "const rc_entry rc_table[] = {"] + ["  {0x%xull, F_%x}," % (a, a) for a in allf] + \
          ["};", "const int rc_table_len = %d;" % len(allf),
           "// hook points (`wrap`), in rc_hook_call's index order",
           "const uint64_t rc_hook_points[] = {"] + ["  0x%xull," % a for a in sorted(wrap)] + \
          ["  0", "};", "const int rc_hook_npoints = %d;" % len(wrap), ""]
    ch.changed += write_if_changed(os.path.join(args.outdir, "table.c"), "\n".join(tab))
    # chunk membership for the manifest
    for a, v in status.items():
        v[3] = ch.where.get(a)
    # stale TUs
    for fn in os.listdir(args.outdir):
        if fn.startswith("part_") and fn.endswith(".c") and fn not in ch.files:
            os.remove(os.path.join(args.outdir, fn))
    write_ninja(args, args.outdir, ch.chunks)
    cnt = {}
    for v in status.values():
        cnt[v[0]] = cnt.get(v[0], 0) + 1
    reasons = {}
    for v in status.values():
        if v[0] == "stub":
            k = re.sub(r"0x[0-9a-f]+", "N", v[1].split(";")[0])[:60]
            reasons[k] = reasons.get(k, 0) + 1
    man = {"functions": len(allf), "dropped": len(drop), "counts": cnt, "chunks": len(ch.chunks),
           "instructions": sum(v[2] for v in status.values()),
           "gen_seconds": round(time.time() - t0, 1),
           "stub_reasons": sorted(reasons.items(), key=lambda kv: -kv[1])[:60],
           "tus": [{"name": n + ".c", "tso": t, "o1": o, "insns": i, "funcs": f} for n, t, o, i, f in ch.chunks],
           "per_function": {"%x" % a: v for a, v in sorted(status.items())}}
    json.dump(man, open(os.path.join(args.outdir, "manifest.json"), "w"))
    print("generated %d functions (%s) in %d TUs (%d rewritten), %.1fs"
          % (len(allf), cnt, len(ch.chunks), ch.changed, time.time() - t0))


if __name__ == "__main__":
    main()
