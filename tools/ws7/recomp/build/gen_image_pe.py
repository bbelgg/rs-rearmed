#!/usr/bin/env python3
"""Whole-image generator for 32-bit PE images (xlat/x86_32.py): what gen_image.py is for the
Mac image.

Usage: venv/bin/python -I gen_image_pe.py IMAGE OUTDIR [options]
  --jobs N, --chunk-insns N, --obj-dir DIR, --cflags "...", --opt -O2, --batch N
                    as for gen_image.py
  --skip FILE       addresses (hex, one per line) an override module defines F_<addr> for

Output in OUTDIR:
  part_<addr>.c     the translated functions (rc32_gen.h), chunked like gen_image.py
  table.c           rc32_table (sorted guest address -> F_<addr>)
  imports.c         one thunk I_<slot> per IAT slot, and rc32_imports. A thunk calls
                    rc32_import_call(c, k): runtime/rc32_imports.c runs the runtime's own
                    implementation of a few kernel32/ntdll functions and fails for the rest
                    (the Win32 seams are not part of the front end); a test runner provides
                    its own.
  decls.h, build.ninja (libgame_rc.a), manifest.json (per function: status, instructions,
                    callee-cleaned bytes, inferred convention; discovery and coverage totals).
"""
import argparse
import collections
import json
import multiprocessing as mp
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
RECOMP = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, RECOMP)
sys.path.insert(0, HERE)
import gen_image as G  # noqa: E402  (shared: Chunker, write_ninja, stub_text, read_addrs)

PRELUDE = ("// Generated by tools/ws7/recomp/build/gen_image_pe.py from original 32-bit x86 machine code.\n"
           "// Derived from the input image: build output only, never commit. Do not edit; regenerate.\n"
           '#include "rc32_gen.h"\n\n')
G.PRELUDE = PRELUDE

_tr = None


def _init(img, funcs, resume):
    global _tr
    from xlat.x86_32 import Translator32
    _tr = Translator32(img, functions=funcs)
    _tr.resume = resume


def _work(batch):
    from xlat.common import Unsupported
    out = []
    for f in batch:
        try:
            lines = _tr.function(f, _tr.img.exports.get(f))
            n = int(re.search(r": (\d+) instructions", lines[0]).group(1))
            info = convention(_tr, f)
            out.append((f, "ok", "", n, "\n".join(lines), sorted(_tr.callees), sorted(_tr.imports_used), info))
        except Unsupported as e:
            out.append((f, "stub", str(e).split(": ", 1)[-1][:300], 1, None, [], [], None))
        except Exception as e:  # translator bug: still must link
            out.append((f, "stub", "internal error: %s: %s" % (type(e).__name__, e), 1, None, [], [], None))
    return out


def convention(tr, f):
    """Callee-cleaned bytes (from `ret N`) and the registers read before written on the path from
    the entry (ecx: thiscall or fastcall, edx too: fastcall). An inference, recorded for
    symbols.map; translated code does not depend on it."""
    from capstone import x86
    seen, _ = tr.discover(f)
    rets = {i.operands[0].imm & 0xffff if i.operands else 0 for i in seen.values() if i.mnemonic == "ret"}
    live, written = set(), set()
    a = f
    for _ in range(64):
        i = seen.get(a)
        if i is None:
            break
        try:
            rd, wr = i.regs_access()
        except Exception:
            break
        for r in rd:
            n = i.reg_name(r)
            if n in ("ecx", "cx", "cl", "ch", "edx", "dx", "dl", "dh"):
                k = "ecx" if "c" in n else "edx"
                if k not in written and not (i.mnemonic == "xor" and len(i.operands) == 2
                                             and i.operands[0].type == i.operands[1].type == x86.X86_OP_REG
                                             and i.operands[0].reg == i.operands[1].reg):
                    live.add(k)
        for r in wr:
            n = i.reg_name(r)
            if n in ("ecx", "edx"):
                written.add(n)
        if i.mnemonic in ("call", "ret", "jmp") or x86.X86_GRP_JUMP in i.groups:
            break
        a += i.size
    pops = max(rets) if rets else None
    conv = "fastcall" if {"ecx", "edx"} <= live else "thiscall" if "ecx" in live else \
        ("stdcall" if pops else "cdecl")
    return {"pops": pops, "conv": conv}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("outdir")
    ap.add_argument("--jobs", type=int, default=os.cpu_count())
    ap.add_argument("--skip", action="append", default=[])
    ap.add_argument("--chunk-insns", type=int, default=40000)
    ap.add_argument("--obj-dir", default=None)
    ap.add_argument("--cflags", default="")
    ap.add_argument("--opt", default="-O2")
    ap.add_argument("--batch", type=int, default=24)
    args = ap.parse_args()
    args.cflags = ("-DRC_GUEST32 " + args.cflags).strip()
    args.lto, args.prof, args.prof_dep = "", "", None
    args.obj_dir = args.obj_dir or os.path.join(args.outdir, "obj")
    os.makedirs(args.outdir, exist_ok=True)
    t0 = time.time()
    from xlat.x86_32 import Translator32
    tr = Translator32(args.image)
    starts = list(tr.fsorted)
    resume = {f: v for f, v in tr.resume.items()}
    disc = dict(tr.discovery)
    imports = dict(tr.imports)
    exports = dict(tr.img.exports)
    del tr
    skip = set()
    for p in args.skip:
        skip |= G.read_addrs(p)
    todo = [f for f in starts if f not in skip]
    batches = [todo[i:i + args.batch] for i in range(0, len(todo), args.batch)]
    ch = G.Chunker(args.outdir, args.chunk_insns, [], set())
    status, callees, used = {}, set(), set()
    conv = {}

    def place(a, st, reason, n, text):
        if st == "stub":
            text = G.stub_text(a, reason)
        ch.add(a, n, text, [])
        status[a] = [st, reason, n, None]

    with mp.Pool(args.jobs, _init, (args.image, starts, resume)) as pool:
        for res in pool.imap(_work, batches):
            for a, st, reason, n, text, cs, us, info in res:
                place(a, st, reason, n, text)
                callees.update(cs)
                used.update(us)
                if info:
                    conv[a] = info
    known = set(status) | skip
    for t in sorted(callees - known):
        place(t, "stub", "callee 0x%x is not a function start" % t, 1, None)
    ch.flush()
    for s in skip:
        status[s] = ["skipped", "override", 0, None]
    allf = sorted(set(status))
    for a, v in status.items():
        v[3] = ch.where.get(a)
    w = G.write_if_changed
    w(os.path.join(args.outdir, "decls.h"), "\n".join(
        ["// generated: prototypes of every translated function", '#include "rc32.h"'] +
        ["void F_%x(rc_ctx *c);" % a for a in allf]) + "\n")
    w(os.path.join(args.outdir, "table.c"), "\n".join(
        [PRELUDE.rstrip("\n"), '#include "decls.h"', "const rc32_entry rc32_table[] = {"] +
        ["  {0x%xu, F_%x}," % (a, a) for a in allf] + ["};", "const int rc32_table_len = %d;" % len(allf), ""]))
    slots = sorted(imports)
    w(os.path.join(args.outdir, "imports.c"), "\n".join(
        [PRELUDE.rstrip("\n"), "void rc32_import_call(rc_ctx *c, int k);"] +
        ["void I_%x(rc_ctx *c) { rc32_import_call(c, %d); }  // %s" % (s, k, imports[s]) for k, s in enumerate(slots)] +
        ["const rc32_import rc32_imports[] = {"] +
        ['  {0x%xu, "%s", I_%x},' % (s, imports[s], s) for s in slots] +
        ["  {0, 0, 0}", "};", "const int rc32_imports_len = %d;" % len(slots), ""]))
    for fn in os.listdir(args.outdir):
        if fn.startswith("part_") and fn.endswith(".c") and fn not in ch.files:
            os.remove(os.path.join(args.outdir, fn))
    G.write_ninja(args, args.outdir, ch.chunks + [("imports", False, False, 0, 0)])
    cnt = collections.Counter(v[0] for v in status.values())
    reasons = collections.Counter()
    for v in status.values():
        if v[0] == "stub":
            reasons[re.sub(r"0x[0-9a-f]+", "N", v[1].split(";")[0])[:60]] += 1
    convs = collections.Counter(c["conv"] for c in conv.values())
    man = {"image": os.path.basename(args.image), "functions": len(allf), "counts": dict(cnt),
           "instructions": sum(v[2] for v in status.values() if v[0] == "ok"),
           "discovery": disc, "conventions": dict(convs), "imports": len(slots), "imports_called": len(used),
           "exports": len(exports), "chunks": len(ch.chunks), "gen_seconds": round(time.time() - t0, 1),
           "stub_reasons": reasons.most_common(60),
           "per_function": {"%x" % a: v + [conv.get(a)] for a, v in sorted(status.items())}}
    json.dump(man, open(os.path.join(args.outdir, "manifest.json"), "w"), indent=0)
    print("generated %d functions (%s) in %d TUs, %.1fs; discovery %s; conventions %s"
          % (len(allf), dict(cnt), len(ch.chunks), time.time() - t0, disc, dict(convs)))


if __name__ == "__main__":
    main()
