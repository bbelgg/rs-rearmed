#!/usr/bin/env python3
"""Whole-image generator for 32-bit PE images (xlat/x86_32.py): what gen_image.py is for the
Mac image.

Usage: venv/bin/python -I gen_image_pe.py IMAGE OUTDIR [options]
  --jobs N, --chunk-insns N, --obj-dir DIR, --cflags "...", --opt -O2, --batch N
                    as for gen_image.py
  --skip FILE       addresses (hex, one per line) an override module defines F_<addr> for. A
                    line `ADDR wrap`: the function is still translated, as W_<addr>, and the
                    override module's F_<addr> (which every call and rc32_table reach) runs
                    native code around it and calls W_<addr> for the original
  --target ID       the hook points of tools/targets/ID (names/hooks.list; main image only): each
                    is translated as W_<addr>, and table.c defines F_<addr>, which runs the hooks
                    registered at run time around it (runtime/rc_hook.h). On a function --skip
                    also names, the override module defines N_<addr> instead of F_<addr>, and
                    the hooks run around that, so a mod sees the function the game now has
  --wrappers TSV    a packer's import-call sites (xlat/x86_32.py read_wrappers): each is
                    translated as the `call/jmp [slot]` it replaced; an import the image's IAT
                    lacks gets a thunk of its own (after the IAT's), one whose name the table
                    leaves empty fails at run time (rc32_wrapper_unresolved)
  --inner JSON      edits and mid points (xlat/inner.py) in place of the target's, for the tests
                    (test/x86/innercases.py): {"edits": [[addr, group, "LEN:CHECK", "EDIT"]], "mids": [[addr,
                    point, [continuation addrs], name]]}, the edits as edits.map has them
  --module NAME     an image that shares the process with others (a DLL beside the game):
                    every global this tree defines is prefixed NAME_ (NAME_rc32_table,
                    NAME_rc32_imports, NAME_rc32_mod, NAME_I_<slot>), so several trees link into
                    one binary; the runtime loads each with rc32_image_add(&NAME_rc32_mod, ...).
                    Without it the names are the plain ones (the main image: the game)

Every translated TU is compiled with -DRC_MO_TSO (x86 total store order, runtime/rc.h), the game's
and each DLL's alike: without it guest loads and stores are plain C accesses, clang hoists the load
out of a spin loop (`b .` in the object code) and arm64 reorders what the game publishes to its
other threads. As on the Mac, the whole image: the code that relies on it is not in a few components.

Output in OUTDIR:
  part_<addr>.c     the translated functions (rc32_gen.h), chunked like gen_image.py
  table.c           rc32_table (sorted guest address -> F_<addr>) and rc32_mod, the image's
                    descriptor for the runtime (runtime/rc32.h), and the hook points: their
                    F_<addr>, rc_hook_points, and what each one's code removes (rc_hook_code_pops)
  imports.c         one thunk I_<slot> per IAT slot (and wrapper-table slot), and rc32_imports. A
                    thunk calls rc32_import_thunk(c, &rc32_mod, k): the export of another loaded
                    image when one provides the import, else the host: rc32_import_call(c, k)
                    for the main image (runtime/rc32_imports.c runs the runtime's own
                    implementation of a few kernel32/ntdll functions and fails for the rest; the
                    Win32 seams are not part of the front end; a test runner provides its own),
                    rc32_host_import for a --module image.
  decls.h, build.ninja (libgame_rc.a), manifest.json (per function: status, instructions,
                    callee-cleaned bytes, inferred convention; discovery and coverage totals).
"""
import argparse
import collections
import json
import multiprocessing as mp
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
RECOMP = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, RECOMP)
sys.path.insert(0, HERE)
import gen_image as G  # noqa: E402  (shared: Chunker, write_ninja, stub_text, read_addrs)

PRELUDE = ("// Generated by tools/ws7/recomp/build/gen_image_pe.py from original 32-bit x86 machine code.\n"
           "// Derived from the input image: build output only, never commit. Do not edit; regenerate.\n"
           '#include "rc32_gen.h"\n\n')
G.PRELUDE = PRELUDE

_tr = None


def _init(img, funcs, resume, flag_callees, data_code, wrappers, prefix="", inline_interlocked=False, inner=None):
    global _tr
    from xlat.x86_32 import Translator32
    _tr = Translator32(img, functions=funcs, wrappers=wrappers)
    _tr.set_inner(*(inner or ({}, {})))
    _tr.thunk_prefix = prefix + "I_"
    _tr.inline_interlocked = inline_interlocked
    _tr.resume = resume
    _tr.flag_callees = flag_callees
    _tr.set_data_code(data_code)


def _work(batch):
    from xlat.common import TableError, Unsupported
    out = []
    for f in batch:
        try:
            lines = _tr.function(f, _tr.img.exports.get(f))
            n = int(re.search(r": (\d+) instructions", lines[0]).group(1))
            info = convention(_tr, f)
            out.append((f, "ok", "", n, "\n".join(lines), sorted(_tr.callees), sorted(_tr.imports_used), info,
                        sorted(_tr.inner_done)))
        except TableError as e:   # an edit or mid point as the tables have it: the build stops (main)
            out.append((f, "table", "0x%x: %s" % (f, e), 1, None, [], [], None, []))
        except Unsupported as e:
            out.append((f, "stub", str(e).split(": ", 1)[-1][:300], 1, None, [], [], None, []))
        except Exception as e:  # translator bug: still must link
            out.append((f, "stub", "internal error: %s: %s" % (type(e).__name__, e), 1, None, [], [], None, []))
    return out


def convention(tr, f):
    """Callee-cleaned bytes (from `ret N`) and the registers read before written on the path from
    the entry (ecx: thiscall or fastcall, edx too: fastcall). An inference, recorded for
    symbols.map; translated code does not depend on it."""
    from capstone import x86
    seen, _ = tr.discover(f)
    rets = {i.operands[0].imm & 0xffff if i.operands else 0 for i in seen.values() if i.mnemonic == "ret"}
    live, written = set(), set()
    a = f
    for _ in range(64):
        i = seen.get(a)
        if i is None:
            break
        try:
            rd, wr = i.regs_access()
        except Exception:
            break
        for r in rd:
            n = i.reg_name(r)
            if n in ("ecx", "cx", "cl", "ch", "edx", "dx", "dl", "dh"):
                k = "ecx" if "c" in n else "edx"
                if k not in written and not (i.mnemonic == "xor" and len(i.operands) == 2
                                             and i.operands[0].type == i.operands[1].type == x86.X86_OP_REG
                                             and i.operands[0].reg == i.operands[1].reg):
                    live.add(k)
        for r in wr:
            n = i.reg_name(r)
            if n in ("ecx", "edx"):
                written.add(n)
        if i.mnemonic in ("call", "ret", "jmp") or x86.X86_GRP_JUMP in i.groups:
            break
        a += i.size
    pops = max(rets) if rets else None
    conv = "fastcall" if {"ecx", "edx"} <= live else "thiscall" if "ecx" in live else \
        ("stdcall" if pops else "cdecl")
    return {"pops": pops, "conv": conv}


def inner_tables(target):
    """The target's edits and mid points (tools/targets: edits.map, mids.map), as xlat/inner.py takes them."""
    sys.path.insert(0, os.path.join(RECOMP, "..", "..", "targets"))
    import targets
    try:
        return targets.inner_points(targets.Target(target), targets.name_lists())
    except targets.TargetError as e:
        sys.exit("gen_image_pe.py: %s" % e)


def check_inner(inner, placed, tables):
    """Every edit and mid point has to be in the translated code: a missing one (its function a stub, or no
    function reaching it) or one a table error refused stops the build."""
    edits, mids = inner
    bad = list(tables)
    bad += ["edit %s at 0x%x: no translated function has it" % (e[4], a) for a, e in sorted(edits.items()) if a not in placed]
    bad += ["mid point %s at 0x%x: no translated function has it" % (m[2], a) for a, m in sorted(mids.items())
            if a not in placed]
    if bad:
        sys.exit("gen_image_pe.py: the target's edits and mid points:\n  " + "\n  ".join(bad))


def hook_points(target):
    """The hook points of a target (tools/targets), sorted: rc_hook_call's index order."""
    sys.path.insert(0, os.path.join(RECOMP, "..", "..", "targets"))
    import targets
    t = targets.Target(target)
    return sorted(a for a in (t.addr(n) for n in targets.name_lists().get("hooks", [])) if a is not None)


def check_hook_prototypes(target, conv):
    """Says which hook points' prototypes disagree with the function's own `ret N`: hooks on them are refused
    at run time (rc32_hook.c), and the table wants a look."""
    import targets
    t = targets.Target(target)
    for n in targets.name_lists().get("hooks", []):
        if t.addr(n) is None:
            continue
        abi, code = targets.hook_abi(t, n), (conv.get(t.addr(n)) or {}).get("pops")
        if abi and abi["pops"] >= 0 and code is not None and abi["pops"] != code:
            print("warning: hook point %s: its prototype has %d bytes of arguments, its code removes %d"
                  % (n, abi["pops"], code), file=sys.stderr)


def hook_table(hooks, native, conv):
    """The lines of table.c for the hook points. Without hooks registered (rc_hook_on) a point is one load
    and a branch more than the function: a hot one must not show on the game thread."""
    if not hooks:
        return []
    if len(hooks) > 256:   # runtime/rc_hook.c: MAX_POINTS, what rc_hook_on[] and the slots are indexed up to
        sys.exit("gen_image_pe.py: %d hook points, and the runtime has room for 256 (rc_hook.c: MAX_POINTS)" % len(hooks))
    L = ['#include "rc_hook.h"', ""]
    for k, a in enumerate(hooks):
        fn = "%s_%x" % ("N" if a in native else "W", a)
        L.append("void F_%x(rc_ctx *c) { if (__builtin_expect(rc_hook_on[%d], 0)) rc_hook_call(%d, c, %s); else %s(c); }"
                 % (a, k, k, fn, fn))
    pops = [(conv.get(a) or {}).get("pops") for a in hooks]
    return L + ["", "// hook points, in rc_hook_call's index order",
                "const uint64_t rc_hook_points[] = {"] + ["  0x%xull," % a for a in hooks] + \
        ["  0", "};", "const int rc_hook_npoints = %d;" % len(hooks), "",
         "// what each one's `ret N`s remove, -1 unknown (rc32_hook.c checks the prototypes against it)",
         "int rc_hook_code_pops(int index) {",
         "  static const short pops[] = {%s};" % ", ".join(str(-1 if p is None else p) for p in pops),
         "  return pops[index];", "}", ""]


def check_image(target, image):
    """As gen_image.py's check: the install stops on another image, a hand build gets this warning."""
    sys.path.insert(0, os.path.join(RECOMP, "..", "..", "targets"))
    import hashlib
    import targets
    want = targets.Target(target).info.get("image_sha256")
    if not want:
        return
    with open(image, "rb") as f:
        got = hashlib.sha256(f.read()).hexdigest()
    if got != want:
        print("gen_image_pe.py: warning: %s is not the image target %s was made for (SHA-256 %s, expected %s). "
              "A capture's image can differ; one with pages missing builds and crashes at the start."
              % (image, target, got, want), file=sys.stderr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("outdir")
    ap.add_argument("--jobs", type=int, default=os.cpu_count())
    ap.add_argument("--skip", action="append", default=[])
    ap.add_argument("--chunk-insns", type=int, default=40000)
    ap.add_argument("--obj-dir", default=None)
    ap.add_argument("--cflags", default="")
    ap.add_argument("--opt", default="-O2")
    ap.add_argument("--batch", type=int, default=24)
    ap.add_argument("--wrappers", default=None)
    ap.add_argument("--module", default=None)
    ap.add_argument("--target", default=None)
    ap.add_argument("--inner", default=None)
    args = ap.parse_args()
    if args.module is not None and not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", args.module):
        ap.error("--module: a C identifier")
    P = args.module + "_" if args.module else ""
    if args.target and not args.module:
        check_image(args.target, args.image)
    # the chunker declares what each TU calls: the thunks carry the prefix
    G.SYM_RE = re.compile(r"\b((?:%s)?[FI]_[0-9a-f]+)\(c\)" % re.escape(P))
    args.cflags = ("-DRC_GUEST32 " + args.cflags).strip()
    args.lto, args.prof, args.prof_dep = "", "", None
    args.obj_dir = args.obj_dir or os.path.join(args.outdir, "obj")
    os.makedirs(args.outdir, exist_ok=True)
    t0 = time.time()
    if args.target:
        os.environ["RC_TARGET"] = args.target    # xlat/relaxed.py reads the target's functions when it is imported
    from xlat.x86_32 import Translator32, read_wrappers
    wrappers = read_wrappers(args.wrappers) if args.wrappers else None
    tr = Translator32(args.image, wrappers=wrappers)
    starts = list(tr.fsorted)
    resume = {f: v for f, v in tr.resume.items()}
    flag_callees = set(tr.flag_callees)
    data_code = list(tr.data_code)
    disc = dict(tr.discovery)
    imports = dict(tr.imports)
    slots = tr.import_slots()
    exports = dict(tr.img.exports)
    del tr
    skip, wrap = set(), set()
    for p in args.skip:
        skip |= G.read_addrs(p, None, wrap)
    skip -= wrap
    if wrap and P:
        ap.error("--skip: `wrap` lines are for the main image only (not with --module)")
    hooks = hook_points(args.target) if args.target else []
    if hooks and P:
        ap.error("--target: hook points are for the main image only (not with --module)")
    for h in hooks:
        if h not in starts:
            ap.error("--target: hook point 0x%x is not a function start of this image" % h)
    native = (skip | wrap) & set(hooks)     # the override module's N_<addr> is the function
    wrap |= set(hooks) - skip
    todo = [f for f in starts if f not in skip]
    batches = [todo[i:i + args.batch] for i in range(0, len(todo), args.batch)]
    ch = G.Chunker(args.outdir, args.chunk_insns, [(0, 1 << 32)], set(), wrap)   # every function: RC_MO_TSO
    status, callees, used = {}, set(), set()
    conv = {}

    def place(a, st, reason, n, text):
        if st == "stub":
            text = G.stub_text(a, reason)
        if a in wrap:   # the original under another name; the override module's F_<a> calls it
            text = text.replace("void F_%x(rc_ctx *c) {" % a, "void W_%x(rc_ctx *c) {" % a, 1)
            st = "wrapped" if st == "ok" else st
        ch.add(a, n, text, [])
        status[a] = [st, reason, n, None]

    print("  0/%d functions, %.0fs" % (len(todo), time.time() - t0), file=sys.stderr, flush=True)
    inner = inner_tables(args.target) if args.target and not P else ({}, {})
    if args.inner:     # the tests' own (test/x86/innercases.py): JSON {"edits": [[addr, group, "LEN:CHECK", "EDIT"]],
        # "mids": [[addr, point, [continuations], name]]}, in place of a target's
        sys.path.insert(0, os.path.join(RECOMP, "..", "..", "targets"))
        import targets
        d = json.load(open(args.inner))
        inner = ({e[0]: (e[1],) + targets.parse_edit(e[2], e[3], "edit %x" % e[0]) + ("edit %x" % e[0],)
                  for e in d.get("edits", [])}, {m[0]: (m[1], m[2], m[3]) for m in d.get("mids", [])})
    placed, table_errors = set(), []
    with mp.Pool(args.jobs, _init, (args.image, starts, resume, flag_callees, data_code, wrappers, P,
                                    bool(args.target), inner)) as pool:
        done = 0
        for res in pool.imap(_work, batches):
            for a, st, reason, n, text, cs, us, info, ins in res:
                placed.update(ins)
                if st == "table":
                    table_errors.append(reason)
                    st = "stub"
                place(a, st, reason, n, text)
                callees.update(cs)
                used.update(us)
                if info:
                    conv[a] = info
            done += len(res)
            # progress as gen_image.py prints it (the installer reads "  N/M functions")
            if (done // args.batch) % 50 == 0 or done == len(todo):
                print("  %d/%d functions, %.0fs" % (done, len(todo), time.time() - t0), file=sys.stderr, flush=True)
    check_inner(inner, placed, table_errors)
    known = set(status) | skip
    for t in sorted(callees - known):
        place(t, "stub", "callee 0x%x is not a function start" % t, 1, None)
    ch.flush()
    for s in skip:
        status[s] = ["skipped", "override", 0, None]
    allf = sorted(set(status))
    for a, v in status.items():
        v[3] = ch.where.get(a)
    w = G.write_if_changed
    w(os.path.join(args.outdir, "decls.h"), "\n".join(
        ["// generated: prototypes of every translated function", '#include "rc32.h"'] +
        ["void F_%x(rc_ctx *c);" % a for a in allf] + ["void W_%x(rc_ctx *c);" % a for a in sorted(wrap)] +
        ["void N_%x(rc_ctx *c);" % a for a in sorted(native)]) + "\n")
    # the descriptor: the main image's host is rc32_import_call (the shims' dispatcher); a
    # module's imports that no other image exports go to rc32_host_import
    w(os.path.join(args.outdir, "table.c"), "\n".join(
        [PRELUDE.rstrip("\n"), '#include "decls.h"', "const rc32_entry %src32_table[] = {" % P] +
        ["  {0x%xu, F_%x}," % (a, a) for a in allf] + ["};", "const int %src32_table_len = %d;" % (P, len(allf))] +
        ["extern const rc32_import %src32_imports[];" % P, "extern const int %src32_imports_len;" % P] +
        (["void rc32_import_call(rc_ctx *c, int k);"] if not P else []) +
        ['rc32_module %src32_mod = {"%s", %src32_table, &%src32_table_len, %src32_imports, &%src32_imports_len, %s, 0};'
         % (P, args.module or "", P, P, P, P, "0" if P else "rc32_import_call"), ""] + hook_table(hooks, native, conv)))
    w(os.path.join(args.outdir, "imports.c"), "\n".join(
        [PRELUDE.rstrip("\n"), "extern rc32_module %src32_mod;" % P] +
        ["void %sI_%x(rc_ctx *c) { rc32_import_thunk(c, &%src32_mod, %d); }  // %s" % (P, s, P, k, imports[s])
         for k, s in enumerate(slots)] +
        ["const rc32_import %src32_imports[] = {" % P] +
        ['  {0x%xu, "%s", %sI_%x},' % (s, imports[s], P, s) for s in slots] +
        ["  {0, 0, 0}", "};", "const int %src32_imports_len = %d;" % (P, len(slots)), ""]))
    for fn in os.listdir(args.outdir):
        if fn.startswith("part_") and fn.endswith(".c") and fn not in ch.files:
            os.remove(os.path.join(args.outdir, fn))
    G.write_ninja(args, args.outdir, ch.chunks + [("imports", False, False, 0, 0)])
    cnt = collections.Counter(v[0] for v in status.values())
    reasons = collections.Counter()
    for v in status.values():
        if v[0] == "stub":
            reasons[re.sub(r"0x[0-9a-f]+", "N", v[1].split(";")[0])[:60]] += 1
    convs = collections.Counter(c["conv"] for c in conv.values())
    man = {"image": os.path.basename(args.image), "module": args.module, "functions": len(allf), "counts": dict(cnt),
           "instructions": sum(v[2] for v in status.values() if v[0] == "ok"),
           "discovery": disc, "conventions": dict(convs), "imports": len(slots), "imports_called": len(used),
           "exports": len(exports), "chunks": len(ch.chunks), "gen_seconds": round(time.time() - t0, 1),
           "stub_reasons": reasons.most_common(60),
           "per_function": {"%x" % a: v + [conv.get(a)] for a, v in sorted(status.items())}}
    json.dump(man, open(os.path.join(args.outdir, "manifest.json"), "w"), indent=0)
    if hooks:
        check_hook_prototypes(args.target, conv)
    print("generated %d functions (%s) in %d TUs, %.1fs; discovery %s; conventions %s"
          % (len(allf), dict(cnt), len(ch.chunks), time.time() - t0, disc, dict(convs)))


if __name__ == "__main__":
    main()
