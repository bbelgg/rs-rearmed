static inline uint8_t rc32_aes_mul(uint8_t x, uint8_t y) {   // in GF(2^8)
  uint8_t r = 0;
  for (; y; y >>= 1, x = (uint8_t)((x << 1) ^ ((x >> 7) * 0x1b)))
    if (y & 1) r ^= x;
  return r;
}
// MixColumns (inv: InvMixColumns) of each column.
static inline void rc32_aes_mix(uint8_t *s, int inv) {
  static const uint8_t m[2][4] = {{2, 3, 1, 1}, {14, 11, 13, 9}};
  for (int c = 0; c < 4; c++) {
    uint8_t a[4], *k = s + 4 * c;
    memcpy(a, k, 4);
    for (int r = 0; r < 4; r++)
      k[r] = rc32_aes_mul(a[r], m[inv][0]) ^ rc32_aes_mul(a[(r + 1) & 3], m[inv][1]) ^
             rc32_aes_mul(a[(r + 2) & 3], m[inv][2]) ^ rc32_aes_mul(a[(r + 3) & 3], m[inv][3]);
  }
}
// aesenc / aesenclast (dec = 0), aesdec / aesdeclast (dec = 1): (Inv)ShiftRows, (Inv)SubBytes,
// (Inv)MixColumns unless last, then the round key.
static inline rc_v128 rc32_aes_round(rc_v128 st, rc_v128 key, int dec, int last) {
  uint8_t s[16], t[16];
  memcpy(s, &st, 16);
  for (int k = 0; k < 16; k++) {
    int r = k & 3, c = k >> 2;
    t[k] = dec ? rc32_aes_isbox[s[4 * ((c - r) & 3) + r]] : rc32_aes_sbox[s[4 * ((c + r) & 3) + r]];
  }
  if (!last) rc32_aes_mix(t, dec);
  rc_v128 v;
  memcpy(&v, t, 16);
  return v ^ key;
}
static inline rc_v128 rc32_aesimc(rc_v128 a) {
  uint8_t s[16];
  memcpy(s, &a, 16);
  rc32_aes_mix(s, 1);
  memcpy(&a, s, 16);
  return a;
}
static inline uint32_t rc32_aes_subword(uint32_t w) {
  return (uint32_t)rc32_aes_sbox[w & 0xff] | (uint32_t)rc32_aes_sbox[(w >> 8) & 0xff] << 8 |
         (uint32_t)rc32_aes_sbox[(w >> 16) & 0xff] << 16 | (uint32_t)rc32_aes_sbox[w >> 24] << 24;
}
// aeskeygenassist: SubWord of dwords 1 and 3, and each rotated right by 8 xor rcon.
static inline rc_v128 rc32_aeskeygenassist(rc_v128 a, uint32_t rcon) {
  uint32_t x1 = rc32_aes_subword((uint32_t)(a[0] >> 32)), x3 = rc32_aes_subword((uint32_t)(a[1] >> 32));
  uint32_t r1 = ((x1 >> 8) | (x1 << 24)) ^ rcon, r3 = ((x3 >> 8) | (x3 << 24)) ^ rcon;
  return (rc_v128){x1 | (uint64_t)r1 << 32, x3 | (uint64_t)r3 << 32};
}

