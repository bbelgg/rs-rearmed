#!/usr/bin/env python3
"""Generate imports.c for the Learn & Play binary from iat_resolved.json.

Since VMProtect stripped the PE's IAT, gen_image_pe.py generates an empty imports list.
This script replaces it with the 231 resolved IAT slots, so rc32_image_load fills the
guest IAT and rc32_icall dispatches imports correctly. Each thunk calls
rc32_import_thunk(c, &rc32_mod, k), as gen_image_pe.py's own do: another loaded image's export
when one provides the import, else the shims (rc32_import_call). The image built by lp_image.py
carries its import directory, so this is only for an older iat_resolved.json.

Usage: python3 gen_iat_imports.py IAT_RESOLVED.json OUTPUT_DIR
"""
import json
import os
import sys


def main():
    iat_path = sys.argv[1]
    outdir = sys.argv[2]

    with open(iat_path) as f:
        iat = json.load(f)

    # Sort by slot address
    slots = sorted(iat.items(), key=lambda x: int(x[0], 16))

    lines = [
        "// Generated by win-x86/build/gen_iat_imports.py from iat_resolved.json.",
        '// Import thunks for the Learn & Play binary (231 resolved IAT slots).',
        '#include "rc32_gen.h"',
        "",
        "extern rc32_module rc32_mod;",
        "",
    ]

    # One thunk per IAT slot
    for k, (slot_hex, info) in enumerate(slots):
        slot = int(slot_hex, 16)
        dll = info["dll"].lower()
        name = info["name"]
        label = "%s!%s" % (dll, name)
        lines.append("void I_%x(rc_ctx *c) { rc32_import_thunk(c, &rc32_mod, %d); }  // %s" % (slot, k, label))

    lines.append("")
    lines.append("const rc32_import rc32_imports[] = {")
    for k, (slot_hex, info) in enumerate(slots):
        slot = int(slot_hex, 16)
        dll = info["dll"].lower()
        name = info["name"]
        label = "%s!%s" % (dll, name)
        lines.append('  {0x%xu, "%s", I_%x},' % (slot, label, slot))
    lines.append("  {0, 0, 0}")
    lines.append("};")
    lines.append("const int rc32_imports_len = %d;" % len(slots))
    lines.append("")

    out = os.path.join(outdir, "imports.c")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("Generated %s: %d import thunks" % (out, len(slots)))


if __name__ == "__main__":
    main()
