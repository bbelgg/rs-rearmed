#!/usr/bin/env python3
"""Vtable layout of the Steam interfaces, read from a 32-bit Windows steam_api.dll.

Every flat export SteamAPI_I<Interface>_<Method>(self, ...) of the DLL is a cdecl wrapper that
loads `self` into ecx and calls the interface's virtual method (MSVC thiscall: callee removes its
stack arguments). From its code:

  * the vtable slot: `call [eax + 4 * slot]`, `mov eax, [eax + 4 * slot]; call eax`, or the
    tail `jmp [eax + 4 * slot]`;
  * the stack words the method takes: the wrapper's own arguments after `self` (the highest
    [ebp + X] it reads), plus one when it passes a hidden return pointer (`lea r, [ebp - N];
    push r`: a method returning CSteamID, which MSVC returns through memory for member
    functions).

The game asks for the same interface versions the DLL's flat API was generated for (SteamUser020,
SteamUtils009, SteamClient019, ...), so the layouts carry over. Writes steam32_slots.h.

usage: gen_slots.py <recomp dir (has xlat/)> steam_api.dll > steam32_slots.h
(needs capstone)
"""
import collections
import re
import sys

import capstone
from capstone import x86


def exports(img):
    rva, _ = img.dir(0)
    a = img.base + rva
    _, _, nname, afun, aname, aord = (img.u32(a + 16 + 4 * k) for k in range(6))
    out = {}
    for k in range(nname):
        o = img.u16(img.base + aord + 2 * k)
        out[img.cstr(img.base + img.u32(img.base + aname + 4 * k))] = img.base + img.u32(img.base + afun + 4 * o)
    return out


def analyse(img, md, a):
    """(slot, words, sret) of the flat wrapper at a, or None."""
    off = img.foff(a)
    hi = 8  # end of the highest wrapper argument read ([ebp + 8] is self)
    lea_regs, sret, slot, held = set(), False, None, {}
    for i in md.disasm(img.data[off:off + 512], a):
        for op in i.operands:
            if op.type == x86.X86_OP_MEM and op.mem.base == x86.X86_REG_EBP and op.mem.disp >= 8 \
                    and i.mnemonic != "lea":
                hi = max(hi, op.mem.disp + op.size)
        ops = i.operands
        if i.mnemonic == "lea" and ops[1].mem.base == x86.X86_REG_EBP and ops[1].mem.disp < 0:
            lea_regs.add(ops[0].reg)
        elif i.mnemonic == "push" and ops[0].type == x86.X86_OP_REG and ops[0].reg in lea_regs:
            sret = True
        elif i.mnemonic == "mov" and ops[0].type == x86.X86_OP_REG and ops[1].type == x86.X86_OP_MEM \
                and ops[1].mem.base == x86.X86_REG_EAX and ops[1].mem.index == 0:
            held[ops[0].reg] = ops[1].mem.disp
        if i.mnemonic in ("call", "jmp"):
            o = ops[0]
            if o.type == x86.X86_OP_MEM and o.mem.base == x86.X86_REG_EAX and o.mem.index == 0:
                slot = o.mem.disp
            elif o.type == x86.X86_OP_REG and o.reg in held:
                slot = held[o.reg]
            if slot is not None:
                if i.mnemonic == "jmp":  # tail call: no arguments besides self
                    return slot // 4, 0, False
                break
            if i.mnemonic == "jmp":
                return None
        if i.mnemonic == "ret":
            return None
    if slot is None:
        return None
    words = (hi - 12 + 3) // 4 + (1 if sret else 0)
    return slot // 4, words, sret


# Slots the flat API leaves out (deprecated methods still in the vtable), from the SDK headers.
HOLES = {
    "ISteamClient": {20: ("RunFrame", 0, False), 25: ("DEPRECATED_GetISteamUnifiedMessages", 3, False),
                     32: ("DEPRECATED_Set_SteamAPI_CPostAPIResultInProcess", 1, False),
                     33: ("DEPRECATED_Remove_SteamAPI_CPostAPIResultInProcess", 1, False),
                     34: ("Set_SteamAPI_CCheckCallbackRegisteredInProcess", 1, False)},
    "ISteamUtils": {14: ("RunFrame", 0, False)},
}


def main():
    sys.path.insert(0, sys.argv[1])
    from xlat.pe import Image
    img = Image(sys.argv[2])
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    ifaces = collections.defaultdict(dict)
    for name, a in sorted(exports(img).items()):
        m = re.fullmatch(r"SteamAPI_(ISteam[A-Za-z]+?)_([A-Za-z0-9]+)", name)
        if not m:
            continue
        r = analyse(img, md, a)
        if r is None:
            print("// not understood: %s" % name, file=sys.stderr)
            continue
        slot, words, sret = r
        prev = ifaces[m.group(1)].get(slot)
        if prev and prev[1:] != (words, sret):
            print("// conflict at %s slot %d" % (name, slot), file=sys.stderr)
        ifaces[m.group(1)][slot] = (m.group(2), words, sret)
    print("// Generated by gen_slots.py from the flat API of the game's steam_api.dll: do not edit.")
    print("// Per interface, one entry per vtable slot: method, stack words (MSVC thiscall, callee")
    print("// pops; `this` is in ecx and not counted), and whether a hidden return pointer comes first")
    print("// (a CSteamID result). Slots the flat API lacks are \"?\" with 0 words.")
    print("#ifndef STEAM32_SLOTS_H")
    print("#define STEAM32_SLOTS_H")
    print("typedef struct { const char *name; unsigned char words, sret; } steam32_slotdef;")
    for iface in sorted(ifaces):
        slots = ifaces[iface]
        n = max(slots) + 1
        print("static const steam32_slotdef steam32_%s[%d] = {" % (iface, n))
        for k in range(n):
            nm, w, s = slots.get(k, HOLES.get(iface, {}).get(k, ("?", 0, False)))
            print('    {"%s", %d, %d},  // %d' % (nm, w, int(s), k))
        print("};")
    print("#endif")


if __name__ == "__main__":
    main()
